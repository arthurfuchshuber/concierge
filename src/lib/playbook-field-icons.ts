const BY_SECTION: LucideIcon[] = [House, KeyRound, Wifi, ScrollText, ClipboardList];

/** Ícone da janela do campo. `rowId` é o id da linha do dossiê (`f:chave`, `faq:…`, `prov…`, personalizada). */
export function playbookFieldIcon(rowId: string, sectionIndex: number): LucideIcon {
  if (rowId.startsWith("f:")) {
    const hit = BY_KEY[rowId.slice(2)];
    if (hit) return hit;
  }
  if (rowId.startsWith("faq:")) return CircleHelp;
  if (rowId.startsWith("prov")) return Wrench;
  return BY_SECTION[sectionIndex] ?? FileText;
}
